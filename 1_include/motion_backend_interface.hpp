#pragma once

#include <memory>
#include <string>
#include <functional>

#include "kuka_riveting/geometry_calculator.hpp"
#include "kuka_riveting/trajectory_generator.hpp"

namespace kuka_riveting {

/**
 * @class IMotionBackend
 * @brief Abstraction over "how motion is actually carried out"
 *
 * Phase 4 drove execution with sleep()-based simulation directly inside
 * MotionControlNode. Phase 5 extracts that behavior behind this interface
 * so the same node, state machine, and Action feedback can run against
 * either a simulated backend (development/demo) or the real KRC4 hardware
 * backend, selected purely by a configuration parameter
 * (hardware.use_real_hardware).
 *
 * Calling contract: for a given boring point, MotionControlNode always
 * calls approach_point() -> drill() -> retract() in that order, exactly
 * once each, before moving on. Implementations may rely on this ordering
 * (e.g. to remember the approach pose for retract()).
 */
class IMotionBackend {
public:
    virtual ~IMotionBackend() = default;

    /// Establishes whatever connection/session the backend needs.
    /// Returns false (with error_message set) if the backend cannot be used.
    virtual bool initialize(std::string& error_message) = 0;

    /// Releases any resources/connections acquired in initialize().
    virtual void shutdown() = 0;

    /**
     * @brief Execute smooth travel motion along a pre-computed trajectory
     * @param travel       Trajectory generated by TrajectoryGenerator (Phase 2)
     * @param cancel_check Returns true if execution should abort immediately
     * @return true if travel completed, false if aborted/failed
     */
    virtual bool execute_travel(
        const Trajectory& travel,
        const std::function<bool()>& cancel_check) = 0;

    /// Move to the fine-positioning pose above the given boring point
    virtual bool approach_point(
        const Point3D& target_point,
        const std::function<bool()>& cancel_check) = 0;

    /// Perform the drilling operation at the current (approached) position
    virtual bool drill(const std::function<bool()>& cancel_check) = 0;

    /// Withdraw the tool back to the approach pose above target_point
    virtual bool retract(
        const Point3D& target_point,
        const std::function<bool()>& cancel_check) = 0;

    /// Human-readable backend name, used in status/log messages
    virtual std::string backend_name() const = 0;
};

using MotionBackendPtr = std::shared_ptr<IMotionBackend>;

} // namespace kuka_riveting
